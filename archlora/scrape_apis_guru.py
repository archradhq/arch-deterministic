#!/usr/bin/env python3
"""
archlora/scrape_apis_guru.py

Fetches real-world OpenAPI specs from apis.guru, converts to ArchRad IR
via `archrad ingest openapi`, validates with `archrad validate --json`,
and emits JSONL training pairs.

No GPT-4o needed — the deterministic engine does the conversion.
IR is real, violations are real.

Data hygiene: uses the official APIs.guru list API, a polite User-Agent,
optional per-row license metadata (list + spec info.license when JSON),
a static DATA_NOTICE next to the JSONL, and an optional .attribution.txt.
This is not legal advice — verify upstream terms for your use case.

Usage:
  python scrape_apis_guru.py --dry-run --max-apis 20
  python scrape_apis_guru.py --max-apis 500
  python scrape_apis_guru.py --resume

Requirements:
  pip install requests
  archrad on PATH (npm i -g @archrad/deterministic), or set ARCHRAD_CLI to archrad.cmd,
  or build this package so dist/cli.js exists and node is on PATH.

Output:
  archlora/corpus/apis-guru-scraped.jsonl
  archlora/corpus/apis-guru-scraped.DATA_NOTICE.md  (unless --no-data-notice)
  archlora/corpus/apis-guru-scraped.attribution.txt  (unless --no-attribution)
"""

